function hashPassword(password) {
  const salt = crypto.randomBytes(16);
  const hash = crypto.scryptSync(password, salt, 64);
  return `scrypt$${salt.toString('hex')}$${hash.toString('hex')}`;
}

function verifyPassword(password, stored) {
  const [scheme, saltHex, hashHex] = String(stored).split('$');
  if (scheme !== 'scrypt' || !saltHex || !hashHex) return false;
  const expected = Buffer.from(hashHex, 'hex');
  const actual = crypto.scryptSync(password, Buffer.from(saltHex, 'hex'), expected.length);
  return crypto.timingSafeEqual(expected, actual);
}

// 세션 서명 키: 환경변수 우선, 로컬 개발에서는 data/ 에 생성해 재시작 후에도 유지
function loadSecret() {
  if (process.env.SESSION_SECRET) return process.env.SESSION_SECRET;
  if (USE_PG) throw new Error('SESSION_SECRET 환경변수가 설정되지 않았습니다.');
  fs.mkdirSync(DATA_DIR, { recursive: true });
  const file = path.join(DATA_DIR, '.session-secret');
  if (!fs.existsSync(file)) fs.writeFileSync(file, crypto.randomBytes(32).toString('hex'));
  return fs.readFileSync(file, 'utf8').trim();
}

// CSV 한 줄 파싱 (따옴표 지원)
function parseCsvLine(line) {
  const out = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') quoted = false;
      else cur += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out.map((s) => s.trim());
}

// [[code, title], ...] 를 도서 DB에 반영 (같은 코드는 제목 갱신)
async function upsertBooks(rows, q = null) {
  const clean = new Map();
  for (const [code, title] of rows) {
    if (code && title) clean.set(String(code).trim(), String(title).trim());
  }
  if (!clean.size) return 0;
  const run = async (t) => {
    await insertMany(t, 'books', ['code', 'title'], [...clean], 'ON CONFLICT (code) DO UPDATE SET title = excluded.title');
  };
  if (q) await run(q); else await tx(run);
  return clean.size;
}

function readSeedBooks() {
  const seedFile = path.join(__dirname, 'seed', 'books.csv');
  if (!fs.existsSync(seedFile)) return [];
  const lines = fs.readFileSync(seedFile, 'utf8').replace(/^﻿/, '').split(/\r?\n/).filter(Boolean);
  return lines.map(parseCsvLine).filter((r, i) => !(i === 0 && /코드|code/i.test(r[0])));
}

// 스키마 생성 + 도서·관리자 초기 데이터 (여러 서버가 동시에 시작해도 한 번만 실행되도록 잠금)
async function initSchema(q) {
  await q.query('SELECT pg_advisory_xact_lock(724501)');
  await q.exec(SCHEMA);

  const { n } = await q.get('SELECT COUNT(*)::int AS n FROM books');
  if (n === 0) {
    const count = await upsertBooks(readSeedBooks(), q);
    if (count) console.log(`[seed] 도서 ${count}권 등록`);
  }

  const admin = await q.get("SELECT id FROM users WHERE role = 'admin'");
  if (!admin) {
    const password = process.env.ADMIN_PASSWORD || crypto.randomBytes(6).toString('base64url');
    await q.query(
      `INSERT INTO users (phone, password_hash, name, rank, role, created_at, must_change_pw)
       VALUES ('admin', $1, '관리자', '관리자', 'admin', $2, $3)`,
      [hashPassword(password), kstNow(), process.env.ADMIN_PASSWORD ? 0 : 1]
    );
    // 로컬 개발에서만 초기 비밀번호를 파일로 남긴다
    if (!process.env.ADMIN_PASSWORD && !USE_PG) {
      fs.writeFileSync(path.join(DATA_DIR, 'ADMIN_INITIAL_PASSWORD.txt'), `ID: admin\nPW: ${password}\n`);
    }
    // 환경변수로 지정한 비밀번호는 로그에 남기지 않는다
    const shown = process.env.ADMIN_PASSWORD ? '(ADMIN_PASSWORD 값)' : `${password}  (로그인 후 비밀번호를 변경하세요)`;
    console.log(`[seed] 관리자 계정 생성 - ID: admin / PW: ${shown}`);
  }
}

