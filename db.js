// Postgres 연결, 스키마, 초기 데이터
// - DATABASE_URL 이 있으면 그 Postgres(Supabase)에 연결 (운영·Vercel)
// - 없으면 내장 PGlite(로컬 파일 Postgres)로 개발 (data/pgdata)
const path = require('node:path');
const fs = require('node:fs');
const crypto = require('node:crypto');

const DATA_DIR = process.env.DATA_DIR || path.join(__dirname, 'data');
const USE_PG = !!process.env.DATABASE_URL;

// 모든 시각은 한국시간(KST) 'YYYY-MM-DD HH:MM:SS' 문자열로 저장한다.
function kstNow() {
  return new Date(Date.now() + 9 * 3600e3).toISOString().slice(0, 19).replace('T', ' ');
}

// DATABASE_PASSWORD 가 따로 있으면 연결 문자열의 비밀번호 자리([YOUR-PASSWORD])에 안전하게 끼워 넣는다
// (특수문자가 있어도 깨지지 않도록 URL 인코딩)
function connectionString() {
  const raw = process.env.DATABASE_URL.trim();
  const password = process.env.DATABASE_PASSWORD;
  if (!password) return raw;
  const url = new URL(raw.replace('[YOUR-PASSWORD]', 'x'));
  url.password = encodeURIComponent(password);
  return url.toString();
}

// ── 드라이버: { query(sql, params) → {rows, rowCount}, exec(sql), tx(fn) } ──
let driver;
function getDriver() {
  if (driver) return driver;
  if (USE_PG) {
    const { Pool, types } = require('pg');
    types.setTypeParser(20, (v) => parseInt(v, 10)); // COUNT/SUM(bigint) → number
    const pool = new Pool({
      connectionString: connectionString(),
      ssl: process.env.DATABASE_SSL === '0' ? false : { rejectUnauthorized: false },
      max: Number(process.env.DATABASE_POOL_MAX) || 3,
      idleTimeoutMillis: 10_000,
    });
    const wrap = (c) => ({
      query: async (sql, params) => { const r = await c.query(sql, params); return { rows: r.rows, rowCount: r.rowCount }; },
      exec: async (sql) => { await c.query(sql); },
    });
    driver = {
      ...wrap(pool),
      tx: async (fn) => {
        const client = await pool.connect();
        try {
          await client.query('BEGIN');
          const result = await fn(helpers(wrap(client)));
          await client.query('COMMIT');
          return result;
        } catch (err) {
          await client.query('ROLLBACK').catch(() => {});
          throw err;
        } finally {
          client.release();
        }
      },
      close: () => pool.end(),
    };
  } else {
    const { PGlite } = require('@electric-sql/pglite');
    fs.mkdirSync(DATA_DIR, { recursive: true });
    const pg = new PGlite(path.join(DATA_DIR, 'pgdata'));
    const wrap = (c) => ({
      query: async (sql, params) => { const r = await c.query(sql, params); return { rows: r.rows, rowCount: r.affectedRows ?? r.rows.length }; },
      exec: async (sql) => { await c.exec(sql); },
    });
    driver = {
      ...wrap(pg),
      tx: (fn) => pg.transaction((t) => fn(helpers(wrap(t)))),
      close: () => pg.close(),
    };
  }
  return driver;
}

// all/get/query/exec 를 갖춘 객체 (트랜잭션 안팎 동일하게 사용)
function helpers(q) {
  return {
    query: q.query,
    exec: q.exec,
    all: async (sql, params) => (await q.query(sql, params)).rows,
    get: async (sql, params) => (await q.query(sql, params)).rows[0],
  };
}

const db = {
  query: (sql, params) => getDriver().query(sql, params),
  exec: (sql) => getDriver().exec(sql),
  all: async (sql, params) => (await getDriver().query(sql, params)).rows,
  get: async (sql, params) => (await getDriver().query(sql, params)).rows[0],
  close: () => (driver ? driver.close() : undefined),
};
const tx = (fn) => getDriver().tx(fn);

// 여러 행을 한 번에 INSERT (클라우드 DB 왕복 횟수를 줄인다)
async function insertMany(q, table, cols, rows, returning = '') {
  const out = [];
  const chunk = Math.max(1, Math.floor(30000 / cols.length));
  for (let i = 0; i < rows.length; i += chunk) {
    const part = rows.slice(i, i + chunk);
    const params = [];
    const values = part.map((r) => `(${r.map((v) => { params.push(v); return `$${params.length}`; }).join(',')})`).join(',');
    const res = await q.query(`INSERT INTO ${table} (${cols.join(',')}) VALUES ${values} ${returning}`, params);
    out.push(...res.rows);
  }
  return out;
}

